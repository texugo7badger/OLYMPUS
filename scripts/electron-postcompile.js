/**
 * scripts/electron-postcompile.js
 *
 * Runs after `tsc -p electron/tsconfig.json` to write a tiny
 * `dist-electron-tsc/package.json` marker file. This is required because:
 *
 *   - The project's root `package.json` has `"type": "module"` (Next.js 16
 *     requires ESM for the Next.js server).
 *   - The Electron main process (`electron/main.ts`) is compiled to
 *     CommonJS (because Electron's main process supports CJS more reliably
 *     than ESM, especially for dynamic `require()` calls).
 *   - When Node loads `dist-electron-tsc/main.js`, it sees the root
 *     `package.json`'s `"type": "module"` and treats the file as ESM —
 *     which fails because the compiled code uses `require()`.
 *
 * The fix: write a local `dist-electron-tsc/package.json` with
 * `"type": "commonjs"`. Node's package scope resolution finds this file
 * first and treats all `.js` files in `dist-electron-tsc/` as CommonJS.
 *
 * Idempotent — safe to run multiple times.
 * License: AGPL-3.0-or-later (original OLYMPUS code).
 */

import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const outDir = join(__dirname, '..', 'dist-electron-tsc');
const markerPath = join(outDir, 'package.json');

try {
  if (!existsSync(outDir)) {
    mkdirSync(outDir, { recursive: true });
  }
  // The marker file MUST have `"type": "commonjs"` so Node treats the
  // compiled .js files as CommonJS (matching the tsconfig module setting).
  writeFileSync(
    markerPath,
    JSON.stringify(
      {
        type: 'commonjs',
        // Include a comment-ish field explaining why this file exists.
        // (JSON doesn't allow comments, so we use a private key.)
        _comment:
          'Auto-generated by scripts/electron-postcompile.js. Marks this directory as CommonJS so Node loads the compiled Electron main.js correctly despite the root package.json having "type":"module".',
      },
      null,
      2,
    ) + '\n',
  );
  console.log('[electron-postcompile] wrote', markerPath);

  // ── THE BUILD-COMPLETE STAMP (2026-10-24) ────────────────────────────────
  // `npm run build:app` / `build:linux` = next build && tsc && THIS script.
  // Writing the stamp HERE means it exists ONLY when the whole chain finished
  // — so the Electron main process can trust `.next/standalone` instead of
  // guessing from file existence. Without it a mid-build launch served a
  // PARTIAL standalone (the "tela toda errada" specimen) or a stale one.
  const root = join(__dirname, '..');
  const stampPath = join(root, '.next', '.olympus-build-complete');
  try {
    const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf-8'));
    writeFileSync(
      stampPath,
      JSON.stringify({
        version: pkg.version ?? 'unknown',
        completedAt: new Date().toISOString(),
        standalone: existsSync(join(root, '.next', 'standalone', 'server.js')),
      }, null, 2) + '\n',
    );
    console.log('[electron-postcompile] build-complete stamp:', stampPath);
  } catch (err) {
    // A missing stamp is not fatal — the app degrades to dev mode loudly.
    console.warn('[electron-postcompile] could not write the build-complete stamp:', err?.message ?? err);
  }
} catch (err) {
  console.error('[electron-postcompile] FAILED:', err);
  process.exit(1);
}
