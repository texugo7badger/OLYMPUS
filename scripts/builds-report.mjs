#!/usr/bin/env node
/**
 * builds-report.mjs — v0.0.86: the Build Hub catalog, as a Markdown report.
 *
 * Generated from the live registry (never hand-maintained): counts by category
 * and god, the real gate each build carries, and the optional-key loadouts.
 * Run: npx tsx scripts/builds-report.mjs > docs/BUILD-HUB.md
 *
 * License: AGPL-3.0-or-later (original OLYMPUS code).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { SEED_DESIGN_BUILDS } = await import(path.join(ROOT, 'src/lib/design-builds.ts'));
const { getMcpEnvVarKeys } = await import(path.join(ROOT, 'src/lib/mcp-api-requirements.ts'));
const { loadIntegrationEnv } = await import(path.join(ROOT, 'src/lib/integration-env.ts'));

const env = loadIntegrationEnv();
const EXECUTABLE = /^(build|lint|test|typecheck|visual)$|^(file-exists|file-contains|file-omits|mounted|visual|design-score):/;
const tierOrder = { hot: 0, warm: 1, cold: 2 };
const builds = [...SEED_DESIGN_BUILDS].sort((a, b) => (a.category || '').localeCompare(b.category || '') || a.name.localeCompare(b.name));

const byCategory = {};
const byGod = {};
const byTier = { hot: 0, warm: 0, cold: 0 };
for (const b of builds) {
  const cat = b.category || 'custom';
  byCategory[cat] = (byCategory[cat] || 0) + 1;
  byGod[b.god] = (byGod[b.god] || 0) + 1;
  byTier[b.tier] = (byTier[b.tier] || 0) + 1;
}

const lines = [];
lines.push('# OLYMPUS Build Hub');
lines.push('');
lines.push(`> Generated by \`npm run builds:report\` on ${new Date().toISOString().slice(0, 10)} from the live seed registry. Do not hand-edit.`);
lines.push('');
lines.push('## Phase 0 (v0.0.86)');
lines.push('');
lines.push('| Item | Status | What changed |');
lines.push('|------|--------|--------------|');
lines.push('| H1 cross-god builds | done | `cache-layer` moved to Persephone; `craft-prototype` now equips Athena\'s `ui-designer` |');
lines.push('| H2 `builds:check` | done | every skill (deep discovery), MCP (local + optional) and demigod (leader god) resolves; guidance-only gates fail |');
lines.push('| H3 skill namespace | done | path ids + `skill_alias`; the index gate rejects two paths sharing one id |');
lines.push('| H4 optional-key badge | done | builds whose MCP key is missing show `needs <KEY>` in the hub |');
lines.push('| H5 matrix fallback | done | the 200 `mx-*` entries are on demand (`?matrix=1`), labelled `generated`, never in the default shelf |');
lines.push('| H6 fusions | done | `spec-lifecycle`, `docs-truth`, `asset-pipeline`; `brain-backup` build renamed `vault-backup` |');
lines.push('| Build → dispatch | done | a hop\'s `buildId` (or best god+skill/MCP fit) injects `buildPrompt()` and writes back to `arsenal-resonance.jsonl` |');
lines.push('| 12 new builds | done | eval, RAG, ETL, browser agent, skill scanner, agent audit, mobile, MCP lifecycle, FinOps, canary, learn, artifacts |');
lines.push('');
lines.push('## Catalog');
lines.push('');
lines.push(`**${builds.length} curated builds** · ${byTier.hot} hot · ${byTier.warm} warm · ${byTier.cold} cold.`);
lines.push('');
lines.push('| Category | Builds |');
lines.push('|----------|-------:|');
for (const [cat, n] of Object.entries(byCategory).sort()) lines.push(`| ${cat} | ${n} |`);
lines.push('');
lines.push('| God | Builds |');
lines.push('|-----|-------:|');
for (const [god, n] of Object.entries(byGod).sort((a, b) => b[1] - a[1])) lines.push(`| ${god} | ${n} |`);
lines.push('');
lines.push('## Builds');
lines.push('');
lines.push('| Build | God | Agents | Skills | MCPs | Real gates | Tier |');
lines.push('|-------|-----|--------|--------|------|------------|------|');
for (const b of builds) {
  const gates = b.verify.filter((v) => EXECUTABLE.test(v)).join(', ') || '—';
  const agents = b.demigods.length ? b.demigods.join(', ') : '—';
  const skills = b.skills.length ? b.skills.join(', ') : '—';
  const mcps = b.mcps.length ? b.mcps.join(', ') : '—';
  const keys = b.mcps.flatMap((m) => getMcpEnvVarKeys(m).filter((k) => !env[k]).map((k) => `${m}:${k}`));
  const mcpsCell = keys.length ? `${mcps} (needs ${keys.join(', ')})` : mcps;
  lines.push(`| \`${b.id}\` | ${b.god} | ${agents} | ${skills} | ${mcpsCell} | ${gates} | ${b.tier} |`);
}
lines.push('');
lines.push('## Gates');
lines.push('');
lines.push('A build is only "verified" when at least one check is executable by `src/lib/hop-runtime/verify.ts`:');
lines.push('`build`, `lint`, `test`, `typecheck`, `visual[:json]`, `file-exists:<rel>`, `file-contains:<rel>::<text>`, `file-omits:<rel>::<text>`, `mounted:<artifact>::<entry>`, `design-score:<n>`.');
lines.push('Everything else is prompt guidance and is documented in [BUILD-VERIFY.md](BUILD-VERIFY.md). `builds:check` fails a build with guidance-only checks.');
lines.push('');
lines.push('## Reproduce');
lines.push('');
lines.push('```bash');
lines.push('npm run builds:check      # reference gate (skills, MCPs, demigods, gates)');
lines.push('npm run builds:report     # this document');
lines.push('npm run bench:hops -- --lane <project> --json   # live hop benchmark');
lines.push('```');

process.stdout.write(lines.join('\n') + '\n');
